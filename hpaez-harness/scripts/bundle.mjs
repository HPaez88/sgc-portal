#!/usr/bin/env node
/**
 * hpaez-harness · bundle generator
 *
 * Concatenates the whole harness (manifesto + all skills + templates + docs +
 * hooks) into ONE portable markdown file you can paste into any agent (CodeGPT,
 * Cursor, Codex, etc.) so it operates with the harness discipline.
 *
 *   node scripts/bundle.mjs            → writes dist/HPAEZ-HARNESS-BUNDLE.md
 */
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));

function read(p) { try { return readFileSync(join(ROOT, p), 'utf8'); } catch { return null; } }
function walk(dir, filter) {
  const out = [];
  (function rec(d) {
    let entries; try { entries = readdirSync(join(ROOT, d)); } catch { return; }
    for (const e of entries.sort()) {
      const rel = join(d, e);
      const st = statSync(join(ROOT, rel));
      if (st.isDirectory()) rec(rel);
      else if (filter(rel)) out.push(rel.replace(/\\/g, '/'));
    }
  })(dir);
  return out;
}

const skills = walk('skills', p => basename(p) === 'SKILL.md');
const parts = [];

parts.push(`# hpaez-harness — Full Bundle (v${pkg.version})

> ${pkg.description}
>
> This single file is the entire harness: the operating manual + all ${skills.length} skills + templates + docs.
> Generated by \`scripts/bundle.mjs\`. Do not hand-edit — regenerate instead.

## How to use this in CodeGPT (or any agent)

1. Load this whole file as the agent's context / operating manual for the target project.
2. Treat every **Hard Rule** and **Decision Gate** below as binding, not advisory.
3. When asked to review a project **structurally**, run this order:
   - \`_core/protocol-sync\` — adopt the 3-file rule (code + STATE.md + CHANGELOG.md).
   - \`_core/scope-boundaries\` — know what you may and may not touch.
   - \`_sdd/constitution\` — capture/confirm the project's immutable principles.
   - \`_sdd/plan\` — turn intent into phased plan + diagram (native Mermaid).
   - \`_agents/department\` — delegate by business domain (product/design/engineering/finance/marketing/ops), each owning one surface, returning on the return-contract.
   - \`_quality/verify-loop\` — never mark a task done without physical evidence + passing build.
   - \`_quality/self-correction\` — every correction becomes a written rule in CONSTITUTION.md.
   - \`_meta/skill-security\` — scan any third-party skill/plugin before installing (SkillSpector, fail-closed > 50).
4. Skills load by trigger: read a skill's \`description\` — when the task matches, apply that skill's contract.

---

## Skill index (${skills.length})

`);

const byCat = {};
for (const s of skills) {
  const cat = s.split('/')[1];
  (byCat[cat] ||= []).push(s);
}
for (const cat of Object.keys(byCat).sort()) {
  parts.push(`- **${cat}** — ${byCat[cat].map(s => s.split('/')[2]).join(', ')}`);
}
parts.push('\n---\n\n## Skills (full contracts)\n');

for (const s of skills) {
  parts.push(`\n### \`${s}\`\n\n${read(s)}\n\n---\n`);
}

// Templates
const templates = walk('templates', p => p.endsWith('.md') || p.endsWith('.template'));
parts.push('\n## Templates\n');
for (const t of templates) parts.push(`\n### \`${t}\`\n\n\`\`\`markdown\n${read(t)}\n\`\`\`\n`);

// Docs
parts.push('\n## Docs\n');
for (const d of ['docs/philosophy.md', 'docs/LESSONS.md', 'README.md']) {
  const c = read(d);
  if (c) parts.push(`\n### \`${d}\`\n\n${c}\n\n---\n`);
}

// Hooks (source, so the target repo can wire enforcement)
const hooks = walk('hooks', p => p.endsWith('.js'));
parts.push('\n## Hooks (enforcement — wire in the agent/settings)\n');
for (const h of hooks) parts.push(`\n### \`${h}\`\n\n\`\`\`javascript\n${read(h)}\n\`\`\`\n`);

const outDir = join(ROOT, 'dist');
if (!existsSync(outDir)) mkdirSync(outDir);
const outFile = join(outDir, 'HPAEZ-HARNESS-BUNDLE.md');
const content = parts.join('\n');
writeFileSync(outFile, content, 'utf8');
console.log(`Bundle written: ${outFile}`);
console.log(`  ${skills.length} skills · ${templates.length} templates · ${hooks.length} hooks · ${(content.length / 1024).toFixed(0)} KB`);
